// =============================================================
// tmds_serializer.sv
// Converts one channel's 10-bit parallel TMDS symbol (from
// tmds_encoder.sv) into a real differential serial TMDS output,
// using a cascaded pair of Xilinx OSERDESE2 primitives (7-series
// SelectIO width-expansion mode) followed by an OBUFDS.
//
// *** STATUS: NOT SIMULATED (Icarus cannot model OSERDESE2). ***
// The data-bit mapping was cross-checked against an open-source working 10:1
// OSERDESE2 serializer (ser_10to1.v in
// https://gist.github.com/marklove5102/a4c47f61d3587d6bbb604a187410dcc5):
//   master D1..D8 = tmds_in[0..7]; slave D3 = tmds_in[8], slave D4 = tmds_in[9],
//   all other slave D inputs 0; slave SHIFTOUT1/2 -> master SHIFTIN1/2 (UG953).
// The first version of this file put bits 8/9 on slave D1/D2, which was wrong.
// Bit 0 is transmitted first (LSB first), as TMDS requires.
// The cascade/bit mapping is now reference-checked but the module has still
// never run in a simulator or on hardware: verify in Vivado behavioural
// simulation (UNISIM) or on the board.
//
// Clocking requirement (not generated by this module -- wire in
// a Clocking Wizard / MMCM output): OSERDESE2 in DATA_RATE_OQ=DDR,
// DATA_WIDTH=10 mode needs a serial clock at 5x the pixel clock
// (CLK) and the pixel clock itself (CLKDIV) -- DDR output doubles
// the effective rate, so 5x clock x 2 (DDR) = 10x pixel clock,
// matching the 10 TMDS bits sent per pixel clock period. For a
// 25 MHz pixel clock that means a 125 MHz serial clock.
// =============================================================
module tmds_serializer (
    input  logic        clk_serial,   // 5x pixel clock (e.g. 125 MHz for a 25 MHz pixel clock)
    input  logic        clk_pixel,    // pixel clock (CLKDIV)
    input  logic        rst,
    input  logic [9:0]  tmds_in,      // one channel's encoded symbol from tmds_encoder
    output logic        tmds_out_p,
    output logic        tmds_out_n
);
    logic serial_q;
    logic cascade1, cascade2;

    // Master: drives the actual output (OQ -> OBUFDS). Takes the
    // low 8 bits of the 10-bit symbol.
    OSERDESE2 #(
        .DATA_RATE_OQ   ("DDR"),
        .DATA_RATE_TQ   ("SDR"),
        .DATA_WIDTH     (10),
        .SERDES_MODE    ("MASTER"),
        .TRISTATE_WIDTH (1)
    ) u_oserdes_master (
        .OQ        (serial_q),
        .OFB       (),
        .TQ        (),
        .TFB       (),
        .SHIFTOUT1 (),
        .SHIFTOUT2 (),
        .TBYTEOUT  (),
        .CLK       (clk_serial),
        .CLKDIV    (clk_pixel),
        .D1        (tmds_in[0]),
        .D2        (tmds_in[1]),
        .D3        (tmds_in[2]),
        .D4        (tmds_in[3]),
        .D5        (tmds_in[4]),
        .D6        (tmds_in[5]),
        .D7        (tmds_in[6]),
        .D8        (tmds_in[7]),
        .TCE       (1'b1),
        .OCE       (1'b1),
        .TBYTEIN   (1'b0),
        .RST       (rst),
        .SHIFTIN1  (cascade1),
        .SHIFTIN2  (cascade2),
        .T1        (1'b0), .T2 (1'b0), .T3 (1'b0), .T4 (1'b0)
    );

    // Slave: supplies the 2 extra bits (8 and 9) needed to reach
    // width 10, via the SHIFTOUT1/2 -> master's SHIFTIN1/2 cascade.
    OSERDESE2 #(
        .DATA_RATE_OQ   ("DDR"),
        .DATA_RATE_TQ   ("SDR"),
        .DATA_WIDTH     (10),
        .SERDES_MODE    ("SLAVE"),
        .TRISTATE_WIDTH (1)
    ) u_oserdes_slave (
        .OQ        (),            // unused on the slave
        .OFB       (),
        .TQ        (),
        .TFB       (),
        .SHIFTOUT1 (cascade1),
        .SHIFTOUT2 (cascade2),
        .TBYTEOUT  (),
        .CLK       (clk_serial),
        .CLKDIV    (clk_pixel),
        .D1        (1'b0), .D2 (1'b0),
        .D3        (tmds_in[8]),      // 10:1 width expansion: the two extra bits go on slave D3/D4
        .D4        (tmds_in[9]),      // (NOT D1/D2) -- see header note
        .D5        (1'b0), .D6 (1'b0), .D7 (1'b0), .D8 (1'b0),
        .TCE       (1'b1),
        .OCE       (1'b1),
        .TBYTEIN   (1'b0),
        .RST       (rst),
        .SHIFTIN1  (1'b0),
        .SHIFTIN2  (1'b0),
        .T1        (1'b0), .T2 (1'b0), .T3 (1'b0), .T4 (1'b0)
    );

    OBUFDS u_obufds (
        .I  (serial_q),
        .O  (tmds_out_p),
        .OB (tmds_out_n)
    );
endmodule
